/**
 * Generate the module that loads every support type's own detail renderer.
 *
 * Same problem as `generate-support-registrations.mjs`, one seam over: each type
 * keeps its renderer in its own folder (`Anchor/AnchorRenderer.tsx`), and
 * something has to import all N of them for their registrations to run. A
 * hand-written import list is a second place a type's name is written down in a
 * PATH, so renaming a type breaks the module resolution for every consumer --
 * measured: renaming `anchor` left `registerBuiltinDetailRenderers.ts` pointing
 * at a folder that no longer exists, and because that module is loaded by the
 * renderer, every test that renders anything failed to load (253 tests never
 * ran, from one stale path).
 *
 * So the list is generated from the folders themselves. The output is gitignored
 * and regenerated by `predev` / `prebuild` / `pretest`, so it is never stale when
 * it is read; `supportTypeFolders.test.ts` holds the other half, failing when a
 * declared type's folder provides no `<Folder>Renderer.tsx` for the generator to
 * find.
 *
 * A folder qualifies when it holds a file named after itself suffixed
 * `Renderer` -- `Trunk/TrunkRenderer.tsx`. That convention is the contract.
 *
 * Kept SEPARATE from the registrations barrel on purpose: this one is imported
 * by the renderer, not the store. Each entry closes over live scene state, and
 * pulling render-layer modules into the store's load reaches back into the store
 * it is still building.
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const typesRoot = path.join(repoRoot, 'src', 'supports', 'SupportTypes');
const outputPath = path.join(
      repoRoot, 'src', 'supports', 'detailRenderer', 'generatedDetailRendererImports.ts',
);

/** `Trunk` -> `TrunkRenderer.tsx`. The file a type folder must provide. */
const rendererFileFor = (folder) => `${folder}Renderer.tsx`;

async function discoverRendererFolders() {
      const entries = await fs.readdir(typesRoot, { withFileTypes: true });
      const folders = [];
      for (const entry of entries) {
            if (!entry.isDirectory()) continue;
            // `shared` holds cross-type helpers and is not a type.
            if (entry.name === 'shared') continue;
            const files = await fs.readdir(path.join(typesRoot, entry.name));
            if (!files.includes(rendererFileFor(entry.name))) continue;
            folders.push(entry.name);
      }
      return folders.sort();
}

export async function renderGeneratedDetailRendererImports() {
      const folders = await discoverRendererFolders();
      const imports = folders.map((folder) => {
            const file = rendererFileFor(folder).replace(/\.tsx?$/, '');
            return `import '../SupportTypes/${folder}/${file}';`;
      });

      return `/* AUTO-GENERATED FILE. DO NOT EDIT.
 * Generated by scripts/generate-support-renderers.mjs
 *
 * Loads every support type's own renderer, discovered from the folders under
 * SupportTypes/. There is deliberately no hand-written list here: a type folder
 * that provides its \`<Folder>Renderer.tsx\` is loaded.
 */
${imports.join('\n')}
`;
}

async function main() {
      const source = await renderGeneratedDetailRendererImports();
      await fs.writeFile(outputPath, source, 'utf8');
      const count = (source.match(/^import /gm) ?? []).length;
      console.log(`[generate-support-renderers] wrote ${count} renderer imports`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
      await main();
}
