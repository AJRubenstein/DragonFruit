/**
 * Generate the module that loads every support type's own registration.
 *
 * A support type's folder is where its per-type facts live, and one of those is
 * how it participates in each seam. Something has to import all N folders for
 * their registrations to run, and a hand-written import list is a second place
 * a type's name is written down -- adding a ninth type would silently not load
 * it, which is the failure this refactor exists to remove.
 *
 * So the list is generated from the folders themselves, the same way
 * `generate-plugin-registry.mjs` builds the builtin plugin registry from
 * `plugins/`. The output is gitignored and regenerated by `predev` / `prebuild`
 * / `pretest`, so it is never stale when it is read; `supportTypeFolders.test.ts`
 * holds the other half, failing when a declared type's folder provides no
 * registration for the generator to find.
 *
 * A folder qualifies when it holds a file named after itself and suffixed
 * `Registration` -- `Trunk/trunkRegistration.ts`. That convention is the
 * contract.
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const typesRoot = path.join(repoRoot, 'src', 'supports', 'SupportTypes');
const outputPath = path.join(repoRoot, 'src', 'supports', 'generatedSupportRegistrations.ts');

/** `Trunk` -> `trunkRegistration`. The file a type folder must provide. */
const registrationFileFor = (folder) => `${folder[0].toLowerCase()}${folder.slice(1)}Registration.ts`;

async function discoverTypeFolders() {
      const entries = await fs.readdir(typesRoot, { withFileTypes: true });
      const folders = [];
      for (const entry of entries) {
            if (!entry.isDirectory()) continue;
            // `shared` holds cross-type helpers and is not a type.
            if (entry.name === 'shared') continue;
            const files = await fs.readdir(path.join(typesRoot, entry.name));
            if (!files.includes(registrationFileFor(entry.name))) continue;
            folders.push(entry.name);
      }
      return folders.sort();
}

export async function renderGeneratedSupportRegistrations() {
      const folders = await discoverTypeFolders();
      const imports = folders.map((folder) => {
            const file = registrationFileFor(folder).replace(/\.ts$/, '');
            return `import './SupportTypes/${folder}/${file}';`;
      });

      return `/* AUTO-GENERATED FILE. DO NOT EDIT.
 * Generated by scripts/generate-support-registrations.mjs
 *
 * Loads every support type's own registration module, discovered from the
 * folders under SupportTypes/. There is deliberately no hand-written list here:
 * a type folder that provides its \`<type>Registration.ts\` is loaded.
 */
${imports.join('\n')}
`;
}

async function main() {
      const source = await renderGeneratedSupportRegistrations();
      await fs.writeFile(outputPath, source, 'utf8');
      const count = (source.match(/^import /gm) ?? []).length;
      console.log(`[generate-support-registrations] wrote ${count} registration imports`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
      await main();
}
